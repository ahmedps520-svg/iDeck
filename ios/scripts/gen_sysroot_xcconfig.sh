#!/usr/bin/env bash
# Writes ios/Sysroot.xcconfig with link flags for every framework and
# static GStreamer plugin in UTM's sysroot. QEMU itself is excluded: it is
# embedded and loaded with dlopen at runtime, never linked.
#   gen_sysroot_xcconfig.sh <sysroot-dir>
set -euo pipefail
SYSROOT="${1:?sysroot dir}"
OUT="$(cd "$(dirname "$0")/.." && pwd)/Sysroot.xcconfig"
flags=()
for fw in "$SYSROOT"/Frameworks/*.framework; do
    name="$(basename "$fw" .framework)"
    case "$name" in
        qemu-*-softmmu) continue ;;   # dlopen'ed
    esac
    flags+=("-framework" "\"$name\"")
done
# Static GStreamer plugins used by spice-gtk audio playback.
if [ -d "$SYSROOT/lib/gstreamer-1.0" ]; then
    for a in "$SYSROOT"/lib/gstreamer-1.0/libgst*.a; do
        # Referenced through the build setting, not this script's working
        # directory: Xcode links from ios/, and each target has its own
        # sysroot (JIT vs TCI).
        [ -e "$a" ] && flags+=("\"\$(SYSROOT_DIR)/lib/gstreamer-1.0/$(basename "$a")\"")
    done
fi
{
    echo "// Generated by gen_sysroot_xcconfig.sh from $(basename "$SYSROOT"). Do not edit."
    echo "// -dead_strip_dylibs drops frameworks the app does not reference."
    echo "OTHER_LDFLAGS = \$(inherited) -lc++ -lz -liconv -lresolv -Wl,-dead_strip_dylibs ${flags[*]}"
} > "$OUT"
echo "wrote $OUT (${#flags[@]} link arguments)"
